//! The Flutter-to-Rust bridge for the PaperWarden core.
//!
//! [`api`] is the hand-written contract; `flutter_rust_bridge_codegen`
//! generates `frb_generated.rs` and the Dart side from it. Regenerate after
//! any change to [`api`] (`CONTRIBUTING.md`, "Generated code"); CI fails if the
//! committed bindings differ from a fresh generation.

pub mod api;

// The Android render service's JNI entry point (#59). `#[no_mangle]` and
// taking ownership of file descriptors need `unsafe_code`; both are confined
// to this one reviewed module.
#[cfg(target_os = "android")]
#[allow(
    unsafe_code,
    reason = "JNI export and file-descriptor ownership only; see the module's SAFETY comments"
)]
mod service_jni;

// Generated FFI glue. It is unsafe by nature and does not follow the
// hand-written lint policy, so the exceptions are scoped to this module only.
#[allow(
    unsafe_code,
    missing_docs,
    clippy::all,
    clippy::pedantic,
    clippy::expect_used,
    clippy::indexing_slicing,
    clippy::panic,
    clippy::unwrap_used,
    clippy::mem_forget,
    clippy::todo,
    clippy::unimplemented,
    reason = "generated by flutter_rust_bridge_codegen; reviewed as a unit, not edited by hand"
)]
mod frb_generated;
