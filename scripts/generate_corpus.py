# --- ZIP-based formats -------------------------------------------------------


class _Cp437Info(zipfile.ZipInfo):
    """Writes the file name as raw code page 437 without the UTF-8 flag."""

    def _encodeFilenameFlags(self):  # noqa: N802 - overrides zipfile's private hook
        return self.filename.encode("cp437"), self.flag_bits


def zip_bytes(
    entries: list[tuple[str, bytes]],
    *,
    compression: int = zipfile.ZIP_DEFLATED,
    stored: tuple[str, ...] = (),
    symlinks: tuple[str, ...] = (),
    cp437: tuple[str, ...] = (),
) -> bytes:
    buffer = io.BytesIO()
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")  # duplicate names are deliberate
        with zipfile.ZipFile(buffer, "w") as archive:
            for name, data in entries:
                info = (_Cp437Info if name in cp437 else zipfile.ZipInfo)(name, ZIP_TIME)
                info.filename = name  # keep backslashes zipfile would rewrite on Windows
                info.create_system = 3
                info.external_attr = (0o120777 if name in symlinks else 0o100644) << 16
                info.compress_type = zipfile.ZIP_STORED if name in stored else compression
                archive.writestr(info, data, compresslevel=9)
    return buffer.getvalue()


CONTENT_TYPES_HEAD = (
    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
    '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
    '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
    '<Default Extension="xml" ContentType="application/xml"/>'
)
REL_NS = "http://schemas.openxmlformats.org/package/2006/relationships"
OFFICE_REL = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"
WORD_MAIN = "application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"
W_NS = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"


def relationships(*items: str) -> bytes:
    return (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
        f'<Relationships xmlns="{REL_NS}">{"".join(items)}</Relationships>'
    ).encode()


def word_document(text: str, doctype: str = "", body_text: str | None = None) -> bytes:
    run = body_text if body_text is not None else text
    return (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
        f"{doctype}"
        f'<w:document xmlns:w="{W_NS}"><w:body><w:p><w:r><w:t>{run}</w:t></w:r></w:p></w:body></w:document>'
    ).encode()


def docx(
    text: str = SAMPLE_TEXT,
    *,
    main_type: str = WORD_MAIN,
    extra_types: str = "",
    extra_parts: list[tuple[str, bytes]] | None = None,
    document: bytes | None = None,
) -> bytes:
    parts = [
        ("[Content_Types].xml", (
            CONTENT_TYPES_HEAD
            + f'<Override PartName="/word/document.xml" ContentType="{main_type}"/>'
            + extra_types + "</Types>").encode()),
        ("_rels/.rels", relationships(
            f'<Relationship Id="rId1" Type="{OFFICE_REL}/officeDocument" Target="word/document.xml"/>')),
        ("word/document.xml", document if document is not None else word_document(text)),
    ]
    return zip_bytes(parts + (extra_parts or []))


def xlsx(sheet: bytes | None = None) -> bytes:
    main = "http://schemas.openxmlformats.org/spreadsheetml/2006/main"
    sheet = sheet or (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
        f'<worksheet xmlns="{main}"><sheetData><row r="1">'
        '<c r="A1" t="inlineStr"><is><t>PaperWarden</t></is></c><c r="B1"><v>42</v></c>'
        "</row></sheetData></worksheet>"
    ).encode()
    return zip_bytes([
        ("[Content_Types].xml", (
            CONTENT_TYPES_HEAD
            + '<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>'
            + '<Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>'
            + "</Types>").encode()),
        ("_rels/.rels", relationships(
            f'<Relationship Id="rId1" Type="{OFFICE_REL}/officeDocument" Target="xl/workbook.xml"/>')),
        ("xl/workbook.xml", (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            f'<workbook xmlns="{main}" xmlns:r="{OFFICE_REL}"><sheets>'
            '<sheet name="Sheet1" sheetId="1" r:id="rId1"/></sheets></workbook>').encode()),
        ("xl/_rels/workbook.xml.rels", relationships(
            f'<Relationship Id="rId1" Type="{OFFICE_REL}/worksheet" Target="worksheets/sheet1.xml"/>')),
        ("xl/worksheets/sheet1.xml", sheet),
    ])


def odt(text: str = SAMPLE_TEXT) -> bytes:
    office = "urn:oasis:names:tc:opendocument:xmlns:office:1.0"
    return zip_bytes(
        [
            ("mimetype", b"application/vnd.oasis.opendocument.text"),
            ("META-INF/manifest.xml", (
                '<?xml version="1.0" encoding="UTF-8"?>\n'
                '<manifest:manifest xmlns:manifest="urn:oasis:names:tc:opendocument:xmlns:manifest:1.0" manifest:version="1.2">'
                '<manifest:file-entry manifest:full-path="/" manifest:media-type="application/vnd.oasis.opendocument.text"/>'
                '<manifest:file-entry manifest:full-path="content.xml" manifest:media-type="text/xml"/>'
                "</manifest:manifest>").encode()),
            ("content.xml", (
                '<?xml version="1.0" encoding="UTF-8"?>\n'
                f'<office:document-content xmlns:office="{office}" '
                'xmlns:text="urn:oasis:names:tc:opendocument:xmlns:text:1.0" office:version="1.2">'
                f"<office:body><office:text><text:p>{text}</text:p></office:text></office:body>"
                "</office:document-content>").encode()),
        ],
        stored=("mimetype",),
    )


