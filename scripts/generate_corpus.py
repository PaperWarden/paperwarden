def png(width: int, height: int, pixels: bytes | None = None, *, corrupt_crc: bool = False,
        idat: bytes | None = None) -> bytes:
    def chunk(kind: bytes, data: bytes, bad: bool = False) -> bytes:
        crc = zlib.crc32(kind + data) ^ (0xFFFFFFFF if bad else 0)
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", crc & 0xFFFFFFFF)

    if idat is None:
        rows = b"".join(b"\0" + (pixels or b"")[y * width * 3:(y + 1) * width * 3] for y in range(height))
        idat = zlib.compress(rows, 9)
    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header, corrupt_crc)
            + chunk(b"IDAT", idat) + chunk(b"IEND", b""))


def bmp(width: int, height: int, pixels: bytes) -> bytes:
    row_size = (width * 3 + 3) & ~3
    rows = b""
    for y in range(height - 1, -1, -1):
        row = b"".join(pixels[(y * width + x) * 3:(y * width + x) * 3 + 3][::-1] for x in range(width))
        rows += row + b"\0" * (row_size - len(row))
    info = struct.pack("<IiiHHIIiiII", 40, width, height, 1, 24, 0, len(rows), 2835, 2835, 0, 0)
    return b"BM" + struct.pack("<IHHI", 14 + len(info) + len(rows), 0, 0, 14 + len(info)) + info + rows


def pillow_image(kind: str, **save: object) -> bytes:
    from PIL import Image

    image = Image.new("RGB", (8, 8))
    image.putdata([((x * 32) % 256, (y * 32) % 256, 128) for y in range(8) for x in range(8)])
    buffer = io.BytesIO()
    image.save(buffer, kind, **save)
    return buffer.getvalue()


