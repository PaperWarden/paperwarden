def pdf_stream(data: bytes, extra: str = "") -> bytes:
    return f"<< /Length {len(data)} {extra}>>\nstream\n".encode() + data + b"\nendstream"


def pdf_document(objects: list[bytes], trailer_extra: str = "") -> tuple[bytes, int, list[int]]:
    """Serialise objects 1..n with a correct xref. Returns bytes, xref offset, offsets."""
    out = bytearray(b"%PDF-1.7\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for number, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += f"{number} 0 obj\n".encode() + body + b"\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n".encode()
    for offset in offsets:
        out += f"{offset:010d} 00000 n \n".encode()
    out += (
        f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R {trailer_extra}>>\n"
        f"startxref\n{xref}\n%%EOF\n"
    ).encode()
    return bytes(out), xref, offsets


def page_objects(
    texts: list[str], catalog_extra: str = "", page_extra: str = "", flate: bool = False
) -> list[bytes]:
    """Catalog, page tree, a font, then a page and content stream per text."""
    count = len(texts)
    kids = " ".join(f"{4 + 2 * index} 0 R" for index in range(count))
    objects = [
        f"<< /Type /Catalog /Pages 2 0 R {catalog_extra}>>".encode(),
        f"<< /Type /Pages /Kids [{kids}] /Count {count} >>".encode(),
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    for index, text in enumerate(texts):
        content = f"BT /F1 14 Tf 20 50 Td ({text}) Tj ET".encode()
        stream = pdf_stream(zlib.compress(content, 9), "/Filter /FlateDecode ") if flate else pdf_stream(content)
        objects.append(
            f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 300 100] "
            f"/Resources << /Font << /F1 3 0 R >> >> /Contents {5 + 2 * index} 0 R {page_extra}>>".encode()
        )
        objects.append(stream)
    return objects


